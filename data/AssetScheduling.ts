const parseAssetSchedules = (csvData: string): AssetSchedule[] => {
  const schedules: AssetSchedule[] = [];
  const lines = csvData.trim().split('\n');
  const startIndex = lines[0].includes('JobCardName') ? 1 : 0;

  for (let i = startIndex; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const parts = line.split(',');
    
    if (parts.length >= 4) {
      let jobCardName = parts[0].trim();
      let jobCardCode = parts[1].trim();
      let assetNumber = parts[2].trim();
      let planCode = parts[3].trim();

      const p0 = parts[0].trim();
      const p1 = parts[1].trim();
      const p2 = parts[2].trim();
      const p3 = parts[3].trim();

      // Heuristic detection:
      if (p1.startsWith('EHAL') && p2.startsWith('HC.')) {
          planCode = p0;
          assetNumber = p1;
          jobCardCode = p2;
          jobCardName = p3; 
      } else if (p1.startsWith('HC.') && p2.startsWith('EHAL')) {
          jobCardName = p0;
          jobCardCode = p1;
          assetNumber = p2;
          planCode = p3;
      }
      
      schedules.push({
        jobCardName,
        jobCardCode,
        assetNumber,
        planCode
      });
    }
  }

  return schedules;
};

export const ASSET_SCHEDULES: AssetSchedule[] = parseAssetSchedules(RAW_ASSET_SCHEDULING_DATA);

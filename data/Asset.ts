const parseAssets = (csvData: string): EquipmentEntry[] => {
  const assets: EquipmentEntry[] = [];
  const lines = csvData.trim().split('\n');
  const startIndex = lines[0].includes('AssetNumber') ? 1 : 0;

  for (let i = startIndex; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    const parts = line.split(',');
    if (parts.length >= 2) {
      const code = parts[0].trim();
      const name = parts[1].trim();
      const traditionalName = parts.length > 2 ? parts[2].trim() : '';
      if (code) {
          assets.push({ code, name, traditionalName });
      }
    }
  }
  return assets;
};

export const EQUIPMENT_LIST: EquipmentEntry[] = parseAssets(RAW_ASSET_DATA);
